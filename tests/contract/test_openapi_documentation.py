"""OpenAPI documentation quality contract (SWAGGER-002).

Guards the public-facing Swagger/OpenAPI documentation against regression:
every operation must be genuinely documented, the ApiKeyAuth/Idempotency-Key
UX must stay intact, error responses must reflect this application's real
ErrorEnvelope contract (never FastAPI's default validation shape), and no
internal ticket/ADR marker may leak into public descriptions. Semantic
assertions only -- no snapshot of the whole schema.
"""

