"""Contextual Project Memory idempotency primitives (SM-CTX-001,
Contract v1 SS 36, Architecture SS 28-29).

The ``contextual_memory_idempotency`` ledger is shared by every contextual
mutation (Episodes now, Checkpoints in later Slices) and is separate from the
Cognitive Memory ledger. It never stores the raw ``Idempotency-Key``, the
raw request, or any semantic content:

- the lookup identity is :func:`protect_contextual_idempotency_key`: a
  stable, non-reversible HMAC-SHA-256 of the raw key;
- the request digest is an HMAC-SHA-256 of a canonical request
  (:func:`build_contextual_canonical_request`).

Both reuse the existing ``COGNITIVE_IDEMPOTENCY_HMAC_KEY`` secret (no new
required secret, handoff 09 SS 33) with HMAC domains distinct from each other
and from the Cognitive Memory domain, so no value computed here can ever
collide with a Cognitive Memory digest. The reserved ``sys:`` namespace is
the single project-wide rule (handoff 09 SS 34) -- reuse
:func:`sofias_memory.domain.is_reserved_idempotency_key`.
"""

from __future__ import annotations

import hashlib
import hmac
import json
from dataclasses import dataclass
from uuid import UUID

from sofias_memory.domain.enums import ContextualMemoryOperation

CONTEXTUAL_CANONICAL_REQUEST_DOMAIN = "sofias-memory.contextual-memory.idempotency"
CONTEXTUAL_CANONICAL_REQUEST_VERSION = 1
CONTEXTUAL_IDEMPOTENCY_KEY_DOMAIN = "sofias-memory.contextual-memory.idempotency-key"

CONTEXTUAL_CREATE_OPERATIONS = frozenset(
    {ContextualMemoryOperation.EPISODE_CREATE, ContextualMemoryOperation.CHECKPOINT_CREATE}
)
"""Operations that create a new resource and never target an existing one;
every other contextual operation requires ``target_resource_id``."""


class InvalidContextualIdempotencyRequestError(ValueError):
    """A :class:`ContextualIdempotencyRequest` violates operation/target shape."""

    def __init__(self, reason: str) -> None:
        self.reason = reason
        super().__init__(f"Invalid contextual idempotency request: {reason}")


@dataclass(frozen=True, slots=True)
class ContextualIdempotencyRequest:
    """Already-normalized semantic identity of one contextual mutation.

    The resource type is implied by ``operation``; ``target_resource_id``
    is a structural UUID of that type. ``payload`` holds only the semantic
    fields -- never an embedding, a generated id, a timestamp generated by
    the server, transport metadata, or a secret."""

    operation: ContextualMemoryOperation
    target_resource_id: UUID | None
    payload: dict[str, object]


def build_contextual_canonical_request(request: ContextualIdempotencyRequest) -> str:
    """Stable, domain-separated JSON used only as HMAC input -- never
    persisted or returned."""

    if request.operation in CONTEXTUAL_CREATE_OPERATIONS:
        if request.target_resource_id is not None:
            raise InvalidContextualIdempotencyRequestError(
                f"{request.operation.value} requests must not carry a target_resource_id"
            )
    elif request.target_resource_id is None:
        raise InvalidContextualIdempotencyRequestError(
            f"{request.operation.value} requests require a target_resource_id"
        )

    canonical_object: dict[str, object] = {
        "domain": CONTEXTUAL_CANONICAL_REQUEST_DOMAIN,
        "version": CONTEXTUAL_CANONICAL_REQUEST_VERSION,
        "operation": request.operation.value,
        "target_resource_id": (
            str(request.target_resource_id) if request.target_resource_id is not None else None
        ),
        "payload": request.payload,
    }
    return json.dumps(canonical_object, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def compute_contextual_request_digest(*, secret: bytes, canonical_request: str) -> str:
    """HMAC-SHA-256 hex digest of the canonical contextual request."""

    return hmac.new(secret, canonical_request.encode("utf-8"), hashlib.sha256).hexdigest()


def protect_contextual_idempotency_key(*, secret: bytes, idempotency_key: str) -> str:
    """Stable, non-reversible lookup identity for a caller ``Idempotency-Key``
    (Architecture SS 28: the key is never stored in plain text). The domain
    separator differs from the request-digest domain, so a key's protected
    identity can never equal any request digest."""

    material = json.dumps(
        {"domain": CONTEXTUAL_IDEMPOTENCY_KEY_DOMAIN, "key": idempotency_key},
        sort_keys=True,
        ensure_ascii=False,
        separators=(",", ":"),
    )
    return hmac.new(secret, material.encode("utf-8"), hashlib.sha256).hexdigest()
