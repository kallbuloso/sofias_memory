def test_every_used_tag_has_metadata() -> None:
    schema = openapi_schema()
    documented_tags = {tag["name"] for tag in schema.get("tags", [])}
    used_tags: set[str] = set()
    for _method, _path, operation in _operations(schema):
        used_tags.update(operation.get("tags", []))
    assert used_tags, "expected at least one tagged operation"
    assert used_tags <= documented_tags


