# --- Documentation-only Swagger schema (manual UX finding) ------------------
#
# /docs renders from a separate, human-facing schema (/openapi-docs.json)
# that strips the Idempotency-Key header parameter -- the canonical
# /openapi.json is untouched and remains the source of truth.


def _idempotency_key_params(schema: dict[str, Any]) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for path, path_item in schema["paths"].items():
        for method, operation in path_item.items():
            if method not in HTTP_METHODS:
                continue
            for parameter in operation.get("parameters", []):
                if (
                    parameter.get("in") == "header"
                    and str(parameter.get("name", "")).lower() == "idempotency-key"
                ):
                    found.append((method, path))
    return found


def documentation_schema() -> dict[str, Any]:
    from sofias_memory.app import _documentation_schema

    return _documentation_schema(openapi_schema())


def test_canonical_schema_has_exactly_six_idempotency_key_parameters() -> None:
    canonical = openapi_schema()
    matches = _idempotency_key_params(canonical)
    assert len(matches) == 6
    assert set(matches) == IDEMPOTENCY_KEY_OPERATIONS


def test_documentation_schema_has_zero_idempotency_key_parameters() -> None:
    doc_schema = documentation_schema()
    assert _idempotency_key_params(doc_schema) == []


def test_documentation_schema_does_not_mutate_canonical_schema() -> None:
    canonical_before = openapi_schema()
    idem_before = len(_idempotency_key_params(canonical_before))
    documentation_schema()
    canonical_after = openapi_schema()
    assert len(_idempotency_key_params(canonical_after)) == idem_before == 6


def test_canonical_and_documentation_schemas_share_identical_paths_and_methods() -> None:
    canonical = openapi_schema()
    doc_schema = documentation_schema()
    assert set(canonical["paths"].keys()) == set(doc_schema["paths"].keys())
    for path, path_item in canonical["paths"].items():
        canonical_methods = {m for m in path_item if m in HTTP_METHODS}
        doc_methods = {m for m in doc_schema["paths"][path] if m in HTTP_METHODS}
        assert canonical_methods == doc_methods, path


def test_canonical_and_documentation_schemas_share_identical_bodies_and_responses() -> None:
    canonical = openapi_schema()
    doc_schema = documentation_schema()
    for method, path, operation in _operations(canonical):
        doc_operation = doc_schema["paths"][path][method]
        assert operation.get("requestBody") == doc_operation.get("requestBody"), path
        assert operation.get("responses") == doc_operation.get("responses"), path
        assert operation.get("security") == doc_operation.get("security"), path


def test_only_parameter_difference_between_schemas_is_idempotency_key() -> None:
    canonical = openapi_schema()
    doc_schema = documentation_schema()
    for method, path, operation in _operations(canonical):
        canonical_params = operation.get("parameters", [])
        doc_params = doc_schema["paths"][path][method].get("parameters", [])
        expected_doc_params = [
            p
            for p in canonical_params
            if not (p.get("in") == "header" and str(p.get("name", "")).lower() == "idempotency-key")
        ]
        assert doc_params == expected_doc_params, path


