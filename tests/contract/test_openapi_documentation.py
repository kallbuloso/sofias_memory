# --- Route-specific error documentation (SWAGGER-002 staging fix) -----------
#
# Every status/code pair below was confirmed against the service code that
# actually raises it before being asserted here -- see the route-specific
# error constants in sofias_memory/api/openapi_responses.py and their
# corresponding services (pipeline_submission.py, dataset_delete.py,
# dataset_delete_barrier.py, run_control.py) for the source of truth.


def _response_for(schema: dict[str, Any], method: str, path: str, status: str) -> dict[str, Any]:
    operation = schema["paths"][path][method]
    response: dict[str, Any] = operation["responses"][status]
    return response


def _assert_error_envelope(response: dict[str, Any]) -> None:
    schema_ref = response["content"]["application/json"]["schema"]["$ref"]
    assert schema_ref == "#/components/schemas/ErrorEnvelope"


